"""summarize.py -- Task 6 of the evidence plan: bench/summary.md from the replay's data.

  python bench/summarize.py                     # bench/replay/{results,builds}.csv + bench/ledger.csv
  python bench/summarize.py --results bench/replay/pilot/results.csv \\
                            --builds bench/replay/pilot/builds.csv

Every number in the summary is a count from those files. Two units, kept apart:

- Frequency is per commit: commits that introduced at least one verified critical or
  high regression (verdict true_regression), divided by commits compared.
- Precision is per blocking finding: true_regression divided by every blocking finding
  with a verdict. unclear and true_but_preexisting count against it, as pre-registered.

It reports; it does not apply the pre-registered thresholds. That is Task 8.
"""
import argparse
import csv
import os
import statistics
from collections import Counter, defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
VERDICTS = ["true_regression", "false_positive", "true_but_preexisting", "unclear"]
MIN_VERDICTS = 20   # bench/PREREGISTRATION.md section 4


def rows(path):
    if not path or not os.path.exists(path):
        return []
    with open(path, encoding="utf-8", newline="") as fh:
        return list(csv.DictReader(fh))


def pct(a, b):
    return "{0:.1f}%".format(100.0 * a / b) if b else "n/a"


def p90(xs):
    """Nearest-rank 90th percentile."""
    xs = sorted(xs)
    return xs[min(len(xs) - 1, int(round(0.9 * (len(xs) - 1))))]


def summary(results, builds, ledger, sources):
    out = ["# Replay summary", "",
           "Generated by `bench/summarize.py` from {0}. Every number is a count from those "
           "files.".format(", ".join("`{0}`".format(s) for s in sources)), ""]

    verified = {(r["repo"], r["head_sha"]) for r in ledger
                if r["verdict"] == "true_regression" and r["severity"] in ("critical", "high")}

    out += ["## Sample and frequency (per commit)", "",
            "| Repository | Commits compared | Failed the gate | With a verified regression | Skipped |",
            "|---|---|---|---|---|"]
    compared_all = with_regression_all = 0
    skipped = Counter()
    for repo in sorted({r["repo"] for r in results}):
        mine = [r for r in results if r["repo"] == repo]
        compared = [r for r in mine if r["gate_result"] in ("pass", "fail")]
        failed = sum(r["gate_result"] == "fail" for r in compared)
        hit = sum((repo, r["head_sha"]) in verified for r in compared)
        skipped.update(r["gate_result"] for r in mine if r not in compared)
        compared_all += len(compared)
        with_regression_all += hit
        out.append("| {0} | {1} | {2} | {3} | {4} |".format(repo, len(compared), failed, hit,
                                                            len(mine) - len(compared)))
    out += ["", "**Frequency: {0} of {1} commits compared ({2})**".format(
        with_regression_all, compared_all, pct(with_regression_all, compared_all))]
    if skipped:
        out += ["", "Skipped comparisons, which count toward neither measure: " + ", ".join(
            "{0} {1}".format(n, k) for k, n in sorted(skipped.items())) + "."]
    pending = sum(1 for r in ledger if not r["verdict"])
    if pending:
        out += ["", "{0} blocking finding(s) still have no verdict; frequency counts only "
                    "verified ones.".format(pending)]

    out += ["", "## Precision (per blocking finding)", ""]
    judged = [r for r in ledger if r["verdict"]]
    true = sum(r["verdict"] == "true_regression" for r in judged)
    out.append("**Precision: {0} of {1} blocking findings with a verdict ({2})**".format(
        true, len(judged), pct(true, len(judged))))
    if len(judged) < MIN_VERDICTS:
        out += ["", "Precision is inconclusive: {0} verdicts, {1} needed.".format(len(judged), MIN_VERDICTS)]
    if ledger:
        out += ["", "| Rule | Findings | true_regression | false_positive | true_but_preexisting "
                    "| unclear | No verdict | Precision |", "|---|---|---|---|---|---|---|---|"]
        by_rule = defaultdict(list)
        for r in ledger:
            by_rule[r["rule_id"]].append(r["verdict"])
        for rule in sorted(by_rule):
            v = Counter(by_rule[rule])
            with_verdict = sum(v[k] for k in VERDICTS)
            out.append("| {0} | {1} | {2} | {3} | {4} | {5} | {6} | {7} |".format(
                rule, len(by_rule[rule]), *[v[k] for k in VERDICTS], v[""],
                pct(v["true_regression"], with_verdict)))
        fps = [r for r in ledger if r["verdict"] == "false_positive"]
        if fps:
            out += ["", "False positives:", ""] + ["- {0} `{1}` {2} on {3}: {4}".format(
                r["repo"], r["head_sha"][:10], r["rule_id"], r["url"], r["notes"] or "(no notes)")
                for r in fps]

    out += ["", "## Tool failures (Addendum 1)", ""]
    failed = [b for b in builds if b["status"] != "ok"]
    if not failed:
        out.append("None: every replayed commit was built and audited.")
    else:
        out += ["| Repository | Commits not audited (sitemend failed) | Commits not built | Why |",
                "|---|---|---|---|"]
        for repo in sorted({b["repo"] for b in failed}):
            mine = [b for b in failed if b["repo"] == repo]
            out.append("| {0} | {1} | {2} | {3} |".format(
                repo, sum(b["status"] == "audit_failed" for b in mine),
                sum(b["status"] == "build_failed" for b in mine),
                "; ".join(sorted({b["error"] for b in mine if b.get("error")})) or "see build.log"))

    out += ["", "## Runtime (per commit built and audited)", ""]
    ok = [b for b in builds if b["status"] == "ok"]
    if ok:
        out += ["| Step | Commits | Median s | 90th percentile s |", "|---|---|---|---|"]
        for label, key in (("Build", "build_seconds"), ("Audit", "audit_seconds")):
            xs = [float(b[key]) for b in ok]
            out.append("| {0} | {1} | {2:.1f} | {3:.1f} |".format(label, len(xs), statistics.median(xs), p90(xs)))
    else:
        out.append("No commit was built and audited.")
    return "\n".join(out) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--results", default=os.path.join(HERE, "replay", "results.csv"))
    ap.add_argument("--builds", default=os.path.join(HERE, "replay", "builds.csv"))
    ap.add_argument("--ledger", default=os.path.join(HERE, "ledger.csv"))
    ap.add_argument("--out", default=os.path.join(HERE, "summary.md"))
    args = ap.parse_args(argv)
    root = os.path.dirname(HERE)
    rel = lambda p: os.path.relpath(p, root).replace(os.sep, "/") if os.path.splitdrive(p)[0] == os.path.splitdrive(root)[0] else p
    sources = [rel(p) for p in (args.results, args.builds, args.ledger) if os.path.exists(p)]
    text = summary(rows(args.results), rows(args.builds), rows(args.ledger), sources)
    with open(args.out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("wrote " + args.out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
